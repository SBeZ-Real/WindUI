return function(WindUI)
    local Window=WindUI:CreateWindow({ID="FluentGallery",Title="WindUI · Fluent Gallery",Author="Footagesus",Style="Premium",Layout="Adaptive",Effects="Balanced",AdaptiveQuality=true,Folder="FluentGallery",Size=UDim2.fromOffset(760,540)})
    local Controls=Window:Tab({Title="Controls",Icon="sliders-horizontal"})
    local Advanced=Window:Tab({Title="Data & navigation",Icon="table"})
    local System=Window:Tab({Title="Window & storage",Icon="settings"})
    local count=0
    local status=Controls:Paragraph({Title="Interactive controls",Desc="Activate the controls to update this page."})
    Controls:Button({Title="Run action",Desc="Counts actual activations",Callback=function()count+=1;status:SetDesc("Action count: "..count)end})
    Controls:Toggle({Title="Enable option",Flag="enabled",Value=true,Callback=function(value)status:SetDesc("Enabled: "..tostring(value))end})
    Controls:Slider({Title="Level",Flag="level",Value={Min=0,Max=100,Default=50},Callback=function(value)status:SetDesc("Level: "..value)end})
    Controls:Input({Title="Display name",Flag="name",Value="WindUI",Validator=function(value)return #value<=40,"Use at most 40 characters"end,Callback=function(value)Window:SetTitle(value)end})
    Controls:Dropdown({Title="Layout",Values={"Settings","Compact","Adaptive"},Value="Adaptive",Callback=function(value)Window:SetLayout(value)end})
    Controls:Dropdown({Title="Selection",Values={"One","Two","Three"},Multi=true,Value={"One"},Flag="selection",Callback=function(value)status:SetDesc(table.concat(value,", "))end})
    Controls:Colorpicker({Title="Accent",Default=Color3.fromHex("#60cdff"),Flag="accent",Callback=function(value)Window:SetAccent(value)end})
    Controls:Keybind({Title="Show diagnostics",Value="F8",Callback=function()Window:Dialog({Title="Diagnostics",Content=game:GetService("HttpService"):JSONEncode(Window:GetDiagnostics()),Buttons={{Title="Close"}}})end})
    local progress=Controls:ProgressBar({Title="Completion",Value=0})
    Controls:Button({Title="Advance completion",Callback=function()progress:Set((progress:Get()+10)%110)end})
    Controls:Code({Title="Theme example",Code='Window:SetStyle("Glass")\nWindow:SetMode("Light")'})
    Controls:Divider()
    local group=Controls:Group()
    group:Paragraph({Title="Grouped controls",Desc="Child resources follow their group."})
    group:Toggle({Title="Grouped switch",Value=false,Callback=function(value)status:SetDesc(tostring(value))end})
    local horizontal=Controls:HStack()
    horizontal:Button({Title="Disable action",Callback=function()progress:SetDisabled(true)end})
    horizontal:Button({Title="Enable action",Callback=function()progress:SetDisabled(false)end})
    local vertical=Controls:VStack()
    vertical:Paragraph({Title="Vertical stack"})
    Controls:Section({Title="Media",Opened=true})
    Controls:Image({Image="rbxassetid://8992230677",Height=80})
    Controls:Space()
    local object=Instance.new("Part")
    object.Size=Vector3.new(3,3,3)
    object.Color=Color3.fromRGB(96,205,255)
    Controls:Viewport({Object=object,Interactive=true,Height=220})
    local rows={}
    for index=1,1000 do rows[index]={ID=index,Name="Item "..index,Value=index*3}end
    Advanced:Breadcrumb({Items={"Home","Data","Gallery"},Callback=function(_,index)Window:SelectTab(math.min(index,3))end})
    Advanced:SearchBox({Title="Search this window"})
    Advanced:DataTable({Title="1,000 rows",Columns={{Key="ID",Title="ID"},{Key="Name",Title="Name"},{Key="Value",Title="Value"}},Rows=rows,Flag="table",Multi=true,Callback=function(row)status:SetDesc("Selected: "..row.Name)end})
    Advanced:TreeView({Title="Workspace tree",Flag="tree",Nodes={{ID="design",Title="Design",Children={{ID="themes",Title="Themes"},{ID="controls",Title="Controls"}}},{ID="runtime",Title="Runtime",Children={{ID="windows",Title="Windows"}}}},Callback=function(node)status:SetDesc(node.Title)end})
    Advanced:DatePicker({Title="Date",Flag="date",Callback=function(value)status:SetDesc(string.format("%04d-%02d-%02d",value.Year,value.Month,value.Day))end})
    Advanced:TimePicker({Title="Time",Flag="time",Callback=function(value)status:SetDesc(string.format("%02d:%02d",value.Hour,value.Minute))end})
    Window:RegisterCommand({ID="restore",Title="Restore gallery window",Callback=function()Window:Restore()end})
    Window:RegisterCommand({ID="theme",Title="Open theme studio",Callback=function()Window:ThemeStudio()end})
    Advanced:CommandPalette({Title="Search and commands"})
    Advanced:ContextMenu({Title="Window actions",Items={{Title="Snap left",Callback=function()Window:Snap("Left")end},{Title="Restore",Callback=function()Window:Restore()end}}})
    local function report(ok,message)
        if ok==false then Window:Dialog({Title="Operation failed",Content=tostring(message),Buttons={{Title="Close"}}})end
    end
    local config=Window.ConfigManager:CreateConfig("gallery")
    config:StartAutoSave(0.5)
    System:Paragraph({Title="Configuration storage",Desc=Window.ConfigManager.Persistent and "File adapter: persistent"or"Memory adapter: this session only"})
    System:Button({Title="Save values",Callback=function()report(config:Save())end})
    System:Button({Title="Load values",Callback=function()report(config:Load())end})
    local json=System:Input({Title="Configuration JSON",Type="Textarea",Value=config:Export(),Callback=function()end})
    System:Button({Title="Export values",Callback=function()json:Set(config:Export())end})
    System:Button({Title="Import values",Callback=function()report(config:Import(json.Value))end})
    System:Button({Title="Save workspace",Callback=function()report(Window:SaveWorkspace("Desktop"))end})
    System:Button({Title="Restore workspace",Callback=function()report(Window:LoadWorkspace("Desktop"))end})
    System:Button({Title="Minimize",Callback=function()Window:Minimize()end})
    System:Button({Title="Notify with action",Callback=function()WindUI:Notify({Window=Window,Title="Saved",Content="Configuration is ready to review.",Actions={{Title="View controls",Callback=function()Window:SelectTab(1)end}}})end})
    System:Button({Title="Progress notification",Callback=function()
        local notification=WindUI:Notify({Window=Window,Title="Progress",Progress=0,DedupeKey="gallery-progress"})
        Window.Scope:Run(function()
            WindUI.Creator.Tasks.spawn(function()
                for index=1,10 do task.wait(0.2);if notification.Closed then return end;notification:SetProgress(index/10)end
                notification:Update({Title="Completed",Content="All steps completed"})
            end)
        end)
    end})
    System:Button({Title="Notification center",Callback=function()Window:NotificationCenter()end})
    Window:ThemeStudio()
    Window:SelectTab(1)
    return Window
end
