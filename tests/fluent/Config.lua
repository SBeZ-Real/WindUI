local window=WindUI:CreateWindow({ID="ConfigTest",Title="Configuration",Style="Classic",Effects="Off"})
local tab=window:Tab({Title="Values"})
local slider=tab:Slider({Flag="slider",Value={Min=0,Max=100,Default=20},Callback=function()end})
local date=tab:DatePicker({Flag="date",Value={Year=2026,Month=11,Day=8}})
local time=tab:TimePicker({Flag="time",Value={Hour=9,Minute=30}})
local data=tab:DataTable({Flag="table",Columns={"Name"},Rows={{Name="Alpha"},{Name="Beta"}}})
local tree=tab:TreeView({Flag="tree",Nodes={{ID="root",Title="Root",Children={{ID="child",Title="Child"}}}}})
local key=tab:Keybind({Flag="key",Value="F",Callback=function()end})
local config=window.ConfigManager:CreateConfig("state")
config:StartAutoSave(0.2)
key:Set("G");key:Set("H")
advance(0.3)
assert(config.LastSave and config.LastSave.Persistent==false,"Setter autosave missing")
data:Select(2);data:Sort("Name",true);tree:Expand("root",true);tree:Select("child")
assert(config:Save()~=false)
date:Set({Year=2027,Month=1,Day=1});time:Set({Hour=1,Minute=2});data:Select(1);tree:Select("root");key:Set("J")
assert(config:Load()~=false)
assert(date.Value.Year==2026 and time.Value.Hour==9 and data:GetSelection()[2] and tree.Value=="child" and key.Value=="H","Advanced state not restored")
assert(window.ConfigManager:SavePreset("Desk") and window.ConfigManager:LoadPreset("Desk")~=false)
assert(window:SaveThemePreset("Blue"))
window:SetAccent("#ff5500")
assert(window:LoadThemePreset("Blue")~=false and window.Tokens.Color.Accent~="#ff5500")
local before=window:ExportTheme()
assert(window:SetTokens({Color={Text="broken"}})==false)
assert(window:SetTokens({Radius={Window=-1}})==false)
assert(window:ImportTheme(http:JSONEncode({Style="Glass",Mode="Dark",Tokens={Color={Text=0}}}))==false)
assert(window.Style=="Classic")
assert(config:Import(http:JSONEncode({__version=1.2,__elements={date={__type="DatePicker",value={Year=2025,Month=2,Day=29}}}}))==false)
assert(date.Value.Year==2026,"Invalid import changed state")
window.ConfigManager.Storage:Write(config.Path,"corrupt")
assert(config:Load()==false and config:Save()==false,"Corrupt file overwritten")
assert(window.ConfigManager.Storage:Read(config.Path)=="corrupt")
window.ConfigManager:SetProfile("Other")
assert(window.ConfigManager:CreateConfig("state").Path~=config.Path,"Profiles collide")
assert(window.ConfigManager:CreateConfig("../escape")==false)
local current=window.CurrentConfig
current:Set("nested",{Enabled=true})
assert(current:Save()~=false and current:Load().nested.Enabled)
assert(window:SaveWorkspace("Desktop"))
window:Snap("Left")
assert(window:LoadWorkspace("Desktop"))
window:Destroy()
advance(1)
assert(#warnings==0,table.concat(warnings,"\n"))
print("CONFIG PASS: autosave, advanced values, presets, profiles, workspace, corrupt data preserved")
